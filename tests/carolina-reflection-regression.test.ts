import test from "node:test";
import assert from "node:assert/strict";
import { type FighterId } from "../shared/content";
import { createMatch, emptyInput, stepMatch, type Input } from "../shared/engine";
import { INTRO_TOTAL_TICKS } from "../shared/presentation";
function setup(side: 0 | 1, gap: number, rivalId: FighterId) {
  const configs = [
    { name: "Carolina", fighter: "carolina" as const, wins: 3 },
    { name: "Rival", fighter: rivalId, wins: 3 },
  ] as const;
  const state = createMatch(
    "poliedro",
    side === 0 ? [...configs] : [configs[1], configs[0]],
    "carolina-reflection",
  );
  const inputs: [Input, Input] = [emptyInput(), emptyInput()];
  const advance = (frames: number) => {
    for (let n = 0; n < frames; n++) stepMatch(state, inputs);
  };
  advance(INTRO_TOTAL_TICKS);
  const player = state.players[side],
    rival = state.players[1 - side];
  player.x = side === 0 ? 180 : 900;
  rival.x = player.x + (side === 0 ? gap : -gap);
  player.energy = 100;
  rival.energy = 100;
  return { state, inputs, player, rival, advance, side };
}
function close(actual: number, expected: number) {
  assert.ok(Math.abs(actual - expected) < 1e-8, `${actual} != ${expected}`);
}

test("A real Renny broadcast rebounds to its sender with Carolina ownership and retained damage on both sides", () => {
  for (const side of [0, 1] as const) {
    const r = setup(side, 200, "renny");
    r.inputs[side].actions.special++;
    r.inputs[1 - side].actions.special++;
    let sentDamage: number | undefined;
    let bounced = false;
    for (let n = 0; n < 100; n++) {
      if (n === 23) r.player.attack = null; // Isolate returned projectile from Carolina's melee.
      r.advance(1);
      for (const shot of r.state.projectiles) {
        if (shot.owner !== side) {
          sentDamage ??= shot.damage;
          continue;
        }
        bounced = true;
        assert.equal(shot.direction, side === 0 ? 1 : -1);
        assert.equal(Math.sign(shot.vx), side === 0 ? 1 : -1);
        assert.equal(shot.kind, "broadcast");
        assert.ok(sentDamage !== undefined);
        close(shot.damage, sentDamage);
        assert.equal(shot.returnAfter, undefined);
      }
    }
    assert.ok(bounced);
    close(r.player.hp, 100);
    assert.ok(r.rival.hp < 100, "the sender is hit by its own reflected shot");
    assert.equal(r.player.hits, 1);
    assert.equal(r.rival.hits, 0);
    assert.equal(r.state.projectiles.length, 0);
  }
});

// The probe projectile is generated by Renny's actual special; it is moved away
// while the defender reaches the sampled frame, then positioned before one step.
function reflectionProbe(side: 0 | 1, frame: number, offset: number) {
  const r = setup(side, 400, "renny");
  r.inputs[1 - side].actions.special++;
  r.advance(10);
  assert.equal(r.state.projectiles.length, 1);
  const shot = r.state.projectiles[0];
  r.rival.attack = null;
  shot.y = -500;
  shot.life = 120;
  r.inputs[side].actions.special++;
  r.advance(frame - 1);
  shot.x = r.player.x + r.player.facing * offset;
  shot.y = r.player.y - 75;
  shot.vy = 0;
  r.advance(1);
  return { r, shot };
}

test("Reflected shots respect the sender's front guard and defeat rear guard", () => {
  for (const side of [0, 1] as const) {
    let unguardedHp: number | undefined;
    for (const guard of ["idle", "front", "rear"] as const) {
      const { r, shot } = reflectionProbe(side, 5, 100);
      assert.equal(shot.owner, side, "the probe was reflected");
      const rivalSide = 1 - side;
      r.inputs[rivalSide].block = guard !== "idle";
      if (guard === "rear")
        r.inputs[rivalSide][side === 0 ? "right" : "left"] = true;
      // Start outside the melee range so this only checks the returned projectile.
      r.rival.x = r.player.x + (side === 0 ? 280 : -280);
      r.advance(90);
      close(r.player.hp, 100);
      if (guard === "idle") {
        assert.ok(r.rival.hp < 100);
        unguardedHp = r.rival.hp;
      } else if (guard === "front") close(r.rival.hp, 100);
      else close(r.rival.hp, unguardedHp!);
      assert.equal(r.player.hits, guard === "front" ? 0 : 1);
    }
  }
});
